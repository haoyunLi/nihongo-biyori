export const chapterTalks = new Map();
export const chapterTurns = new Map();
export const chapterSpeech = [];
function register(l, scene, intro, rows) {
  const catalog = [...l.steps.flatMap((s) => s.examples), ...l.dialogue];
  const turns = rows.map(([goal, jp, q, other, aliases = "", base], i) => {
    const model = catalog.find((m) => m.jp === jp);
    if (!model) throw new Error("Chapter reply missing: " + l.id + " " + jp);
    const key = l.id + "." + i,
      first = typeof q === "string" ? line(q) : q,
      alternate = line(other);
    const role =
      (l.id === "c05" && i === 0) || l.id === "f10"
        ? "朋友"
        : talks[scene].role;
    const item = {
      key,
      lesson: l.id,
      scene,
      role,
      goal,
      model,
      first,
      alternate,
      aliases: aliases.split("/").filter(Boolean),
      base,
    };
    chapterTurns.set(key, item);
    chapterSpeech.push(first, alternate);
    return item;
  });
  chapterTalks.set(l.id, { scene, intro, turns });
}
for (const l of lessons) {
  if (material[l.id]) {
    const [scene, intro, rows] = material[l.id];
    register(l, scene, intro, rows);
    continue;
  }
  const alt = extensionAlternate[Number(l.id.slice(1)) - 1];
  const rows = l.quiz.map((q, i) => {
    const prompt = l.steps[i].examples[0],
      model = q.model;
    const node = Object.values(talks[l.scene].nodes).find(
      (n) => n.prompt.jp === prompt.jp,
    );
    const base = node?.edges.find((e) => e.model.jp === model.jp);
    return [
      q.prompt.replace(/^听对方说完。/u, ""),
      model.jp,
      prompt,
      alt[i],
      "",
      base,
    ];
  });
  if (l.id === "x14")
    rows.splice(1, 0, [
      "把已经打开的预约页面递给对方看。",
      "はい、どうぞ。",
      talks.event.nodes.show.prompt,
      "受付の画面を拝見できますか。|うけつけのがめんをはいけんできますか。|能给我看一下预约页面吗？",
      "どうぞ/こちらです",
    ]);
  register(l, l.scene, l.goal, rows);
}
function comparable(text) {
  return normalise(text)
    .replace(/^(すみません|じゃあ|では|はい)/u, "")
    .replace(/1つ|一つ/gu, "ひとつ")
    .replace(/2つ|二つ/gu, "ふたつ")
    .replace(/2枚|二枚/gu, "にまい")
    .replace(/1枚|一枚/gu, "いちまい")
    .replace(
      /(?:ですね|です|をください|ください|でお願いします|お願いします|でおねがいします|おねがいします)$/u,
      "",
    );
}
export function chapterAnswer(item, raw) {
  const input = normalise(raw),
    expected = [item.model.jp, item.model.kana, ...item.aliases].map(normalise);
  const short = comparable(raw);
  if (
    expected.includes(input) ||
    (short && expected.some((e) => comparable(e) === short))
  )
    return { kind: "ok", next: null, replies: [], model: item.model.jp };
  if (
    item.base &&
    item.base.match.test(input) &&
    !/(?:なくて|ではなく|じゃな|要ら|いらない|ません|ないです)/u.test(input)
  )
    return { kind: "ok", next: null, replies: [], model: item.model.jp };
  if (/もう一度|もういちど|もう一回|ゆっくり/u.test(input))
    return { kind: "repeat" };
  return { kind: "unclear" };
}
