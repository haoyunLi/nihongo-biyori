// A stop provides the situation, not a translation of the partner's question.
// Keys point to answers taught in this week; fresh voiced cues are used on the trip.
// The ordinary alternate for the same key becomes the next-day transfer question.
const turn = (id, jp, kana, zh) => ({ id, cue: { jp, kana, zh } });
const stop = (place, setting, ...turns) => ({ place, setting, turns });
const trip = (chapter, title, intro, finish, ...stops) => ({
  chapter,
  title,
  intro,
  finish,
  stops,
  minutes: 5,
  turns: stops.flatMap((s, i) => s.turns.map((t) => ({ ...t, stop: i }))),
});
