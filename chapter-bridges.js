export function addBridges(lessons) {
  const byId = new Map(lessons.map((l) => [l.id, l]));
  for (const [id, [index, text]] of Object.entries(prompts))
    byId.get(id).steps[index].body += " " + text;
  for (const [
    id,
    step,
    prompt,
    options,
    answer,
    why,
    jp,
    listen,
  ] of transitions) {
    const l = byId.get(id);
    const model =
      l.steps.flatMap((s) => s.examples).find((x) => x.jp === jp) ||
      (id === "t03"
        ? { jp, kana: "よやくしました。りんです。", zh: "我订过房。我姓林。" }
        : null);
    if (!model) throw new Error("Missing bridge model " + id + " " + jp);
    l.quiz.push({
      step,
      prompt,
      options,
      answer,
      why,
      model,
      category: "跨章接话与听辨",
      ...(listen ? { listen } : {}),
    });
  }
}
