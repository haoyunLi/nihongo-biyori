export function exitContext(time, index) {
  const when = validProposal(time) ? proposalLines(time).label : "刚约好的时间";
  return exitOptions[index]
    ? "按之前约好的" +
        when +
        "，提议在车站" +
        exitOptions[index].label +
        "碰面。"
    : "已经约好" + when + "。自己挑东、西、南或北口，向朋友提议在那里碰面。";
}
