const editionLine = (s, v) => speechLine(Array.isArray(s) ? s[v] : s);
export function followPlan(week, v) {
  const plan = plans[week - 1];
  if (!plan) return;
  return {
    ...plan,
    ask: speechLine(plan.ask),
    retry: speechLine(plan.retry),
    reply: editionLine(plan.reply, v),
    again: editionLine(plan.again, v),
  };
}
